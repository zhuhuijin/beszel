/** Strips provider quirks: "Munich (Moosach)" -> "Munich", "X, Region" -> "X" */
export function cleanCityName(city: string): string {
	const cleaned = city.split(/[,(·]/)[0].trim()
	return cleaned || city.trim()
}

/** Localized city display name: Chinese mapping for zh locales, cleaned English otherwise */
export function cityDisplayName(city: string | undefined, locale: string): string | null {
	if (!city) return null
	const cleaned = cleanCityName(city)
	if (locale && /^zh/i.test(locale)) {
		return CITY_NAMES_ZH[cleaned.toLowerCase()] ?? cleaned
	}
	return cleaned
}
